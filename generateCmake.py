import os

def generate_cmake_sources():
    src_dir = "src"
    source_extensions = {".cpp", ".h"}

    sources = []

    # Walk through the src directory recursively
    for root, _, files in os.walk(src_dir):
        for file in files:
            ext = os.path.splitext(file)[1]
            if ext in source_extensions:
                # Get relative path from the root project folder
                rel_path = os.path.relpath(os.path.join(root, file), ".")
                # Normalize path separators for CMake (use forward slashes)
                sources.append(rel_path.replace("\\", "/"))

    # Write the results to a separate CMake file
    cmake_content = "# Auto-generated by generate_sources.py\n\n"
    cmake_content += "set(AUTO_SOURCES\n"
    for src in sorted(sources):
        cmake_content += f"    {src}\n"
    cmake_content += ")\n"

    with open("sources.cmake", "w") as f:
        f.write(cmake_content)

    print(f"Successfully generated sources.cmake with {len(sources)} files.")

if __name__ == "__main__":
    generate_cmake_sources()
